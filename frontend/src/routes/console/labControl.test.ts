import { describe, expect, it } from 'vitest'
import { ghostPose, samePose } from '../../robot/ghost'
import { TelemetryBus } from '../../telemetry/bus'
import { validateCalibration, type CalibrationMessage, type Command, type ResponseStatus } from '../../telemetry/contracts'
import fixture from '../../telemetry/fixtures/calibration_full.json'
import { Simulator } from '../../telemetry/sources/simulator'
import { isEmptyChanges, mergeChanges, requestStatus, type SentRequest } from './requests'
import { checkedValue, enableHint, nudgedProfile, responseRange, responseValue, shownProfile } from './robotControl'

/** A fresh copy of the status Wearable Lab really publishes (generated by wearable_test/test_console.py). */
const full = (): CalibrationMessage => structuredClone(fixture) as unknown as CalibrationMessage
type Loose = Record<string, unknown>

describe('the full Wearable Lab status', () => {
  it('passes validation, sections and all', () => {
    expect(validateCalibration(full())).toBeNull()
  })

  it('still passes without the new sections, as from an older Wearable Lab', () => {
    const m = full() as unknown as Loose
    for (const key of ['physical', 'response', 'arm_settings', 'directions', 'coins', 'wearable', 'geometry', 'control_request']) delete m[key]
    expect(validateCalibration(m)).toBeNull()
    for (const key of ['physical', 'response', 'coins']) m[key] = null
    expect(validateCalibration(m)).toBeNull()
  })

  it.each<[string, (m: CalibrationMessage) => void]>([
    ['an unknown robot mode', (m) => { (m.physical as unknown as Loose).mode = 'flying' }],
    ['a short joint table', (m) => { m.physical!.joints.pop() }],
    ['a NaN-like joint angle', (m) => { (m.physical!.joints[0] as unknown as Loose).actual_deg = 'nan' }],
    ['a response speed out of range', (m) => { m.response!.values.speed_deg_s = 400 }],
    ['a joint lead out of range', (m) => { m.response!.values.joint_lead_deg.elbow_flex = 0 }],
    ['a profile index past the list', (m) => { m.response!.profile = 9 }],
    ['an arm length out of range', (m) => { m.arm_settings!.values.hand_cm = 61 }],
    ['an unknown sensor axis', (m) => { (m.arm_settings!.values.axes as Loose).hand = '+W' }],
    ['a missing joint direction', (m) => { delete (m.directions!.reverse as Loose).gripper }],
    ['three coins', (m) => { m.coins!.motors.pop() }],
    ['a coin level over 100%', (m) => { m.coins!.motors[0].percent = 101 }],
    ['a joystick ADC reading over 4095', (m) => { m.wearable!.joystick = { x: 5000, y: 0, nx: 0, ny: 0, pressed: false, fresh: true } }],
    ['a short arm', (m) => { m.geometry!.joints.pop() }],
    ['an enable reply without applied', (m) => { m.control_request = { id: 'x', ok: true, detail: '' } }],
  ])('rejects %s', (_, spoil) => {
    const m = full()
    spoil(m)
    expect(validateCalibration(m)).not.toBeNull()
  })
})

describe('request status', () => {
  const request: SentRequest = { id: 'a', session: 's', at: 1000, sent: true }
  it('waits, then completes on our own reply only', () => {
    expect(requestStatus(request, null, 's', 1500, true)).toMatchObject({ pending: true, done: false, error: '' })
    expect(requestStatus(request, { id: 'a', ok: true, detail: 'Started.' }, 's', 1500, true)).toMatchObject({ done: true, detail: 'Started.' })
    expect(requestStatus(request, { id: 'a', ok: false, detail: 'Calibrate first.' }, 's', 1500, true).error).toBe('Calibrate first.')
  })
  it('waits for applied when asked, and reports a timeout or a restart', () => {
    const accepted = { id: 'a', ok: true, applied: false, detail: 'Enable requested.' }
    expect(requestStatus(request, accepted, 's', 1500, true, true)).toMatchObject({ pending: true, detail: 'Enable requested.' })
    expect(requestStatus(request, { ...accepted, applied: true }, 's', 1500, true, true).done).toBe(true)
    expect(requestStatus(request, accepted, 's', 5000, true, true).error).toMatch(/not confirmed/)
    expect(requestStatus(request, null, 's', 5000, true).error).toMatch(/No confirmation/)
    expect(requestStatus(request, null, 'other', 1500, true).error).toMatch(/restarted/)
    expect(requestStatus({ ...request, sent: false }, null, 's', 1500, true).error).toMatch(/not sent/)
  })
})

describe('tuning changes', () => {
  it('merge, later values winning and joint leads combining', () => {
    const merged = mergeChanges(mergeChanges(null, { speed_deg_s: 100, joint_lead_deg: { elbow_flex: 10 } }),
      { speed_deg_s: 120, joint_lead_deg: { wrist_flex: 4 } })
    expect(merged).toEqual({ speed_deg_s: 120, joint_lead_deg: { elbow_flex: 10, wrist_flex: 4 } })
    expect(isEmptyChanges(null)).toBe(true)
    expect(isEmptyChanges({ joint_lead_deg: {} })).toBe(true)
    expect(isEmptyChanges(merged)).toBe(false)
  })
  it('do not share nested objects with their inputs', () => {
    const first = { joint_lead_deg: { elbow_flex: 10 } }
    const merged = mergeChanges(null, first)
    merged.joint_lead_deg!.elbow_flex = 20
    expect(first.joint_lead_deg.elbow_flex).toBe(10)
  })
})

describe('response profiles and fields', () => {
  const response = (): ResponseStatus => structuredClone(full().response!)
  it('show the pending profile first and step within the list', () => {
    const r = response()
    r.profile = 4
    r.pending = null
    expect(shownProfile(r)).toBe(4)
    expect(nudgedProfile(r, 1)).toBeNull()
    expect(nudgedProfile(r, -1)).toBe(3)
    r.pending = r.values
    r.pending_profile = null
    expect(shownProfile(r)).toBeNull()
    expect(nudgedProfile(r, -1)).toBeNull()
  })
  it('read values and ranges for top-level settings and joint leads', () => {
    const values = response().values
    expect(responseValue(values, 'lead:elbow_flex')).toBe(values.joint_lead_deg.elbow_flex)
    expect(responseValue(values, 'control_hz')).toBe(values.control_hz)
    expect(responseRange('lead:wrist_roll')).toEqual([1, 45])
    expect(responseRange('response_ms')).toEqual([1, 100])
  })
  it('accept only typed numbers within range', () => {
    expect(checkedValue('12.5', [1, 45])).toBe(12.5)
    expect(checkedValue('', [1, 45])).toBeNull()
    expect(checkedValue('46', [1, 45])).toBeNull()
    expect(checkedValue('abc', [1, 45])).toBeNull()
  })
})

describe('enable hints', () => {
  it('name the first thing to fix', () => {
    const m = full()
    const p = m.physical!
    expect(enableHint({ ...m, phase: 'needs_recenter' }, p)).toMatch(/recenter/)
    expect(enableHint(m, { ...p, fresh: false })).toMatch(/stale/)
    expect(enableHint(m, { ...p, mode: 'live' })).toMatch(/STOP/)
    expect(enableHint(m, { ...p, mode: 'off', input_status: 'wearable UI unresponsive' })).toBe('wearable UI unresponsive')
  })
})

describe('the preview ghost', () => {
  it('poses the arm from preview angles and the claw from the measured value', () => {
    const p = full().physical!
    const pose = ghostPose(p, [0, 0, 0, 0, 0, 72])
    expect(pose).toEqual([...p.joints.slice(0, 5).map((j) => j.preview_deg), 72])
    expect(ghostPose(p, null)?.[5]).toBe(50)
    expect(samePose(pose, pose && [...pose])).toBe(true)
  })
  it('hides when any arm joint has no preview', () => {
    const p = full().physical!
    p.joints[2].preview_deg = null
    expect(ghostPose(p, null)).toBeNull()
    expect(ghostPose(null, null)).toBeNull()
  })
})

describe('the simulator', () => {
  it('declines every robot command instead of pretending to apply it', () => {
    const sim = new Simulator(new TelemetryBus())
    const base = { request_id: 'r', session: 's', revision: 0 }
    const commands: Command[] = [
      { type: 'control_robot', action: 'enable_arm', ...base },
      { type: 'tune_robot', profile: 2, ...base },
      { type: 'configure_arm', settings: full().arm_settings!.values, ...base },
      { type: 'set_joint_direction', joint: 'wrist_roll', reverse: true, ...base },
      { type: 'test_haptic_motor', action: 'test', motor: 0, percent: 40, ...base },
    ]
    for (const command of commands) expect(sim.send(command)).toBe(false)
  })
})
